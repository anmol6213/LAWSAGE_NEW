import { renderToStaticMarkup } from 'react-dom/server';
import ReactMarkdown from 'react-markdown';

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// Opens a clean, branded print view. In the print dialog choose "Save as PDF".
export const exportPdf = (question: string | null, answer: string) => {
  const body = renderToStaticMarkup(<ReactMarkdown>{answer}</ReactMarkdown>);
  const w = window.open('', '_blank');
  if (!w) {
    window.alert('Please allow pop-ups for this site to download the PDF.');
    return;
  }
  w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>Lawsage answer</title>
<style>
  body{font-family:Georgia,'Times New Roman',serif;color:#14243A;max-width:720px;margin:40px auto;padding:0 24px;line-height:1.65}
  .brand{display:flex;align-items:center;gap:10px;border-bottom:2px solid #C49A45;padding-bottom:12px;margin-bottom:24px;font-size:20px;font-weight:700}
  .brand span{display:inline-block;width:28px;height:28px;border-radius:7px;background:#14243A;color:#D8B56D;text-align:center;line-height:28px;font-size:16px}
  h1.q{font-size:22px;line-height:1.3;margin:0 0 18px}
  h1,h2,h3{line-height:1.3}
  code{background:#f1f1f1;padding:1px 4px;border-radius:3px}
  blockquote{border-left:3px solid #D8B56D;margin-left:0;padding-left:14px;color:#40608C}
  table{border-collapse:collapse}td,th{border:1px solid #ccc;padding:4px 8px}
  .foot{margin-top:32px;padding-top:12px;border-top:1px solid #ddd;font:12px/1.5 system-ui,sans-serif;color:#667}
</style></head><body>
<div class="brand"><span>⚖</span>Lawsage</div>
${question ? `<h1 class="q">${esc(question)}</h1>` : ''}
${body}
<div class="foot">Generated by Lawsage on ${new Date().toLocaleDateString()}. General legal information, not legal advice. Please verify with the official text or a qualified lawyer.</div>
</body></html>`);
  w.document.close();
  w.focus();
  setTimeout(() => w.print(), 400);
};

export const canShare = () => typeof navigator !== 'undefined' && typeof navigator.share === 'function';

export const shareAnswer = async (question: string | null, answer: string) => {
  const text = `${question ? question + '\n\n' : ''}${answer}\n\n— Lawsage (general information, not legal advice)`;
  try {
    await navigator.share({ title: 'Lawsage answer', text });
  } catch {
    /* user cancelled */
  }
};
